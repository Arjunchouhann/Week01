import java.util.Scanner;
//create DistanceConvertor Class to convert kilometers into miles
public class DistanceConvertor {
	public static void main ( String[]args ) {
		//Create a variable kilometer to indicate distance in kilometers
		double kilometer = 10.8 ;
		//Create a variable miles to indicate distance in miles
		double miles =  kilometer/1.6 ;
		//Print the Distance
		System.out.println("The Distance " + kilometer + " km in miles is " + miles);
	}
}
		
